# NOT BUILT. Kept as a record of a decision, not as a brand in use.
#
# MuseMore was chosen for a day, on the reasoning that a name about the
# plectrum is narrower than what the fork actually carries: the Encore
# importer alone is forty of its hundred and four commits.
#
# It was dropped because the name promises the wrong thing. "MuseScore with
# more in it" commits the fork to being a general distribution of whatever
# upstream has not merged, and that is a maintenance burden nobody signed up
# for: it would mean carrying, rebasing and answering for a growing pile of
# other people's unmerged pull requests, indefinitely.
#
# PlectraScore promises something narrower and keeps it. See
# fork/brand/plectrascore/identity.sh.
#
# Nothing references this file. It stays because the reasoning is worth more
# than the name was, and because the next person to think "why not just call
# it MuseSomething" deserves the answer without having to rediscover it.

